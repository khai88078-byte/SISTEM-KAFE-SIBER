-- 1. Basic 2-Table Join (Customer + SessionLog)
SELECT CUSTOMER.CUSTOMER_NAME, SESSION_LOG.SESSION_ID
FROM CUSTOMER
JOIN SESSION_LOG ON CUSTOMER.CUSTOMER_ID = SESSION_LOG.CUSTOMER_ID;

-- 2. Triple Join (Customer + SessionLog + Computer)
SELECT CUSTOMER.CUSTOMER_NAME, COMPUTER.SPECS, SESSION_LOG.HOURS_PLAYED
FROM CUSTOMER
JOIN SESSION_LOG ON CUSTOMER.CUSTOMER_ID = SESSION_LOG.CUSTOMER_ID
JOIN COMPUTER ON SESSION_LOG.COMPUTER_ID = COMPUTER.COMPUTER_ID;

-- 3. Join with Filters (VIPs using RTX 4090)
SELECT CUSTOMER.CUSTOMER_NAME, COMPUTER.SPECS
FROM CUSTOMER
JOIN SESSION_LOG ON CUSTOMER.CUSTOMER_ID = SESSION_LOG.CUSTOMER_ID
JOIN COMPUTER ON SESSION_LOG.COMPUTER_ID = COMPUTER.COMPUTER_ID
WHERE COMPUTER.SPECS = 'RTX 4090' AND CUSTOMER.MEMBERSHIP_TYPE = 'VIP';