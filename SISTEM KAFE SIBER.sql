CREATE DATABASE SISTEM_KAFE_SIBER;
USE SISTEM_KAFE_SIBER;

CREATE TABLE CUSTOMER (
CUSTOMER_ID VARCHAR (50) PRIMARY KEY,
CUSTOMER_NAME VARCHAR (100) NOT NULL,
MEMBERSHIP_TYPE VARCHAR (50) NOT NULL
);

CREATE TABLE COMPUTER (
COMPUTER_ID VARCHAR (50) PRIMARY KEY,
SPECS VARCHAR (100) NOT NULL,
HOURLY_RATE INT NOT NULL
);

CREATE TABLE SESSION_LOG (
SESSION_ID VARCHAR (50) PRIMARY KEY,
CUSTOMER_ID VARCHAR (50) NOT NULL,
COMPUTER_ID VARCHAR (50) NOT NULL,
HOURS_PLAYED INT NOT NULL,
SESSION_DATE DATE,
FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
FOREIGN KEY (COMPUTER_ID) REFERENCES COMPUTER(COMPUTER_ID)
);

